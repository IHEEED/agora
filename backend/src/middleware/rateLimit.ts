import rateLimit from 'express-rate-limit';
import type { Request } from 'express';

/**
 * Ограничения частоты — по одному на каждое действие, которое создаёт
 * содержимое.
 *
 * Первая версия ставила один общий счётчик на все не-GET запросы к /posts,
 * /comments, /messages, /stories и /reports. Проверка показала, во что это
 * обходится: «не-GET» — это не только «написать». Просмотр записи — POST, и он
 * уходит на каждую пролистанную карточку; «прочитано» — POST на каждое открытие
 * чата; реакции и закрепы — PUT. Тридцать пролистанных записей — и человек на
 * десять минут терял возможность написать хоть слово.
 *
 * Поэтому счётчик стоит на самом маршруте создания, а не на префиксе, и у
 * каждого действия он свой: переписка в темпе спора не должна съедать запас на
 * публикацию записи.
 *
 * Ключ — учётная запись, а не адрес. Мобильные операторы сажают за один
 * внешний адрес тысячи абонентов, и счётчик по адресу запирал бы весь район за
 * одного болтливого соседа. Эти счётчики стоят после requireAuth, поэтому
 * человек уже известен.
 */
function perUser(options: { windowMs: number; limit: number }) {
  return rateLimit({
    ...options,
    standardHeaders: 'draft-7',
    legacyHeaders: false,
    keyGenerator: (req: Request) => req.user!.id,
    message: { error: 'RATE_LIMITED' },
  });
}

/**
 * Числа — на порядок выше живого человека, но на порядки ниже скрипта.
 *
 * Записи: десять за десять минут. Запись — это заголовок и мысль, быстрее её
 * не придумать; десятая подряд — уже рассылка.
 * Комментарии: сорок за десять минут — ответ каждые пятнадцать секунд.
 * Сообщения: сорок в минуту. Переписка идёт очередями коротких реплик, и
 * «ок», «щас», «смотри» подряд — это разговор, а не спам.
 * Истории: двадцать в час. Жалобы: двадцать в час.
 */
export const limitPosts = perUser({ windowMs: 10 * 60_000, limit: 10 });
export const limitComments = perUser({ windowMs: 10 * 60_000, limit: 40 });
export const limitMessages = perUser({ windowMs: 60_000, limit: 40 });
export const limitStories = perUser({ windowMs: 60 * 60_000, limit: 20 });
export const limitReports = perUser({ windowMs: 60 * 60_000, limit: 20 });
