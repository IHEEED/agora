import { supabase } from './supabase';

/**
 * Что из необязательного уже есть в базе.
 *
 * Миграции здесь выполняются руками, в панели Supabase, и между выкладкой кода
 * и выполнением миграции всегда есть промежуток. Обычно это терпимо: новая
 * возможность просто не работает. Но запрос к PostgREST со ссылкой на
 * несуществующую колонку не деградирует — он падает целиком, и вместе с ним
 * падает всё, что этим запросом бралось.
 *
 * Ровно это и случилось с аватарками: `select('id, username, avatar_url')`
 * перестал возвращать что-либо, и в списке переписок у всех вместо имени
 * оказался прочерк. Возможность, которой ещё нет, сломала то, что работало
 * годами.
 *
 * Поэтому один раз при старте спрашиваем базу, что в ней есть, и строим строки
 * выборки от ответа. Проверка ленивая и запоминается: на выдачу это одна
 * лишняя строка кода, а не запрос.
 */

let hasAvatarColumn: boolean | null = null;

/**
 * Есть ли users.avatar_url (миграция 015).
 *
 * Спрашиваем самым дешёвым способом: выбрать колонку с нулевым пределом. Если
 * её нет, PostgREST вернёт ошибку, но строк не тронет, и это ровно тот ответ,
 * который нужен.
 */
export async function probeSchema(): Promise<void> {
  const { error } = await supabase.from('users').select('avatar_url').limit(0);
  hasAvatarColumn = !error;

  if (!hasAvatarColumn) {
    console.warn(
      'users.avatar_url не найдена — аватарки отключены. Выполните миграцию 017 и перезапустите.'
    );
  }
}

/**
 * Поля человека для выдачи.
 *
 * @param extra Что добавить между обязательными полями и аватаркой —
 *              например 'karma' или 'karma, created_at'.
 */
export function userColumns(extra?: string): string {
  const base = extra ? `id, username, ${extra}` : 'id, username';
  // null означает «ещё не спрашивали»: до ответа ведём себя осторожно и
  // аватарку не просим. Проверка идёт при старте, так что это состояние живёт
  // доли секунды и только на самых первых запросах.
  return hasAvatarColumn ? `${base}, avatar_url` : base;
}

/**
 * Тот же набор, но как вложенная связь: `author:users(...)`.
 *
 * @param alias Как назвать связь в ответе — 'author', 'user'.
 * @param hint  Имя внешнего ключа, когда связей между таблицами несколько и
 *              PostgREST не может выбрать сам (ошибка PGRST201).
 */
export function userEmbed(alias: string, hint?: string): string {
  return `${alias}:users${hint ? `!${hint}` : ''}(${userColumns()})`;
}
