import { Agent, setGlobalDispatcher } from 'undici';

/**
 * Переиспользование соединений до Supabase.
 *
 * Самое дорогое в этом приложении — не запросы к базе, а установка соединения до
 * неё. Замеры с этой машины, пять запросов из тех, что собирают ленту:
 *
 *   по одному, по очереди          1023 мс
 *   пять параллельно, как в коде   8219 мс
 *
 * Параллельно медленнее в восемь раз — и это не опечатка. Node открывает на
 * каждый запрос своё TLS-соединение, пять рукопожатий разом уходят в один и тот
 * же узкий канал и мешают друг другу. Ленте на это уходило почти семь секунд, и
 * именно они читались как «всё лагает и тормозит»: анимации были ни при чём,
 * приложение просто ждало ответа.
 *
 * Общий пул с keep-alive снимает рукопожатие со всех запросов, кроме первого:
 *
 *   те же пять параллельно, пул    640 мс
 *
 * connections: 10. Первая версия ставила два, и это была ошибка замера: я мерил,
 * обращаясь к серверу в одиночку, а приложение открыто у нескольких человек и
 * само опрашивает несколько ручек. Под настоящей нагрузкой двойка превращается в
 * очередь. Замеры одного «захода в приложение» — пять запросов разом:
 *
 *   соединений   1 заход   4 захода   8 заходов
 *   2            496 мс    1706 мс    —
 *   6            228 мс     638 мс    1159 мс
 *   8            181 мс     494 мс    1010 мс
 *   10           167 мс     449 мс     719 мс
 *   16           217 мс     337 мс     799 мс
 *
 * Десять — лучшая одиночная задержка и устойчивое поведение под нагрузкой.
 * Шестнадцать выигрывает на четырёх заходах, но проигрывает на одном и на
 * восьми: соединений больше, чем канал тянет одновременно.
 *
 * Важно, что дело было не в параллельности как таковой, а в холодных
 * рукопожатиях: пул сам по себе их не убирает, он только позволяет
 * переиспользовать уже открытые. Поэтому все соединения греются на старте
 * (см. index.ts) — иначе первые запросы снова платят за TLS, и большой пул
 * оказывается хуже маленького.
 *
 * pipelining: 1 намеренно. Конвейеризация выше единицы для HTTP/1.1 в дикой
 * природе ломается на посредниках, и Supabase среди них.
 */
export const HTTP_CONNECTIONS = 10;

setGlobalDispatcher(
  new Agent({
    connections: HTTP_CONNECTIONS,
    // Держим соединение открытым между запросами. Минуты достаточно: реже
    // одного запроса в минуту приложение не спрашивают даже ночью, а держать
    // дольше — платить за простой на стороне Supabase.
    keepAliveTimeout: 60_000,
    keepAliveMaxTimeout: 300_000,
    pipelining: 1,
  })
);
