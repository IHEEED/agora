/**
 * Короткая память сервера.
 *
 * Лента одинакова для всех, кто открыл её в одну и ту же секунду: сортировка не
 * зависит от того, кто спрашивает. Личное в ответе есть — мой голос, мой репост,
 * мои подписки, — но оно приклеивается к записям после выборки и стоит доли
 * миллисекунды. Тяжёлая часть, сама выборка, общая.
 *
 * Десять секунд — не «столько, сколько можно», а осознанный предел. Новая запись
 * должна появляться в ленте почти сразу: человек публикует и тут же смотрит,
 * получилось ли. Десять секунд он спишет на задержку сети, а минуту воспримет
 * как то, что запись пропала. Голоса и комментарии обновляются на месте, не
 * дожидаясь перезагрузки списка, поэтому им этот срок не мешает.
 *
 * Память процесса, а не Redis. Redis нужен, когда серверов несколько и они
 * обязаны видеть одно и то же; здесь сервер один, и лишняя зависимость добавила
 * бы точку отказа ровно там, где мы боремся за скорость.
 */

type Entry = { value: unknown; until: number };

const store = new Map<string, Entry>();

/**
 * Сколько записей держим. Ограничение существует, чтобы карта не росла
 * бесконечно от опечаток в параметрах запроса: каждый новый набор параметров —
 * свой ключ, и без предела их набралось бы столько, сколько запросов.
 */
const MAX_ENTRIES = 200;

/** Сколько живёт запись по умолчанию. */
const DEFAULT_TTL_MS = 10_000;

/**
 * Взять из памяти или посчитать и запомнить.
 *
 * Одновременные запросы за одним и тем же ключом объединяются: в карту кладётся
 * само обещание, а не результат. Без этого десять человек, открывших ленту в
 * одну секунду на холодном кеше, отправили бы десять одинаковых выборок — то
 * есть кеш помогал бы ровно там, где нагрузки нет, и не помогал там, где она
 * есть.
 */
const inFlight = new Map<string, Promise<unknown>>();

export async function cached<T>(
  key: string,
  produce: () => Promise<T>,
  ttlMs: number = DEFAULT_TTL_MS
): Promise<T> {
  const now = Date.now();
  const hit = store.get(key);
  if (hit && hit.until > now) return hit.value as T;

  const running = inFlight.get(key);
  if (running) return running as Promise<T>;

  const task = produce()
    .then((value) => {
      if (store.size >= MAX_ENTRIES) {
        // Выкидываем самую старую по порядку вставки: Map хранит его сам, и это
        // дешевле, чем считать, к чему обращались чаще. При десятисекундной
        // жизни разница между стратегиями вытеснения неразличима.
        const oldest = store.keys().next().value;
        if (oldest !== undefined) store.delete(oldest);
      }
      store.set(key, { value, until: Date.now() + ttlMs });
      return value;
    })
    .finally(() => {
      inFlight.delete(key);
    });

  inFlight.set(key, task);
  return task;
}

/**
 * Забыть всё, что начинается с этой строки.
 *
 * Звать после записи: опубликовал — лента обязана показать это сразу, а не через
 * десять секунд. Именно поэтому кеш и можно ставить так близко к данным: у него
 * есть кто-то, кто знает, когда данные изменились.
 */
export function forget(prefix: string) {
  for (const key of store.keys()) {
    if (key.startsWith(prefix)) store.delete(key);
  }
}
