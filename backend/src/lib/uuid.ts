/**
 * Проверка, что строка — настоящий UUID.
 *
 * Нужна там, где значение из запроса попадает не в параметр, а в текст фильтра
 * PostgREST — в `.or(...)`. Обычный `.eq('col', value)` клиент экранирует сам, и
 * подставить туда ничего нельзя. А `.or()` принимает целую строку на языке
 * фильтров, и она собирается конкатенацией: чужой идентификатор вида
 * `x),and(recipient_id.not.is.null` разрывал фильтр и открывал чужую переписку.
 *
 * UUID из восьми-четыре-четыре-четыре-двенадцати шестнадцатеричных знаков не
 * содержит ни скобок, ни запятых, ни точек — то есть ничего из грамматики
 * фильтра. Убедились, что это UUID, — и подставлять его безопасно.
 */
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function isUuid(value: unknown): value is string {
  return typeof value === 'string' && UUID_RE.test(value);
}
