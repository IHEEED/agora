-- 025: у пересланного сообщения видно, чьё оно было.
--
-- Выполнять в Supabase → SQL Editor целиком. Скрипт идемпотентный.
--
-- Пересылка была копированием без следа: чужая реплика приходила к третьему
-- человеку как твоя собственная. Для пары фраз это мелочь, а для чего угодно
-- спорного — подлог: сказал один, а отвечать пришло другому.
--
-- Ссылка на автора, а не строка с именем. Имя человек меняет, и через месяц
-- подпись под пересланным указывала бы на никого. К тому же по ссылке можно
-- перейти в профиль, а по строке нельзя.
--
-- on delete set null, а не cascade: удалили автора — сообщение остаётся, просто
-- перестаёт быть подписанным. Уносить с собой чужие переписки оно не должно.
alter table public.messages
  add column if not exists forwarded_from uuid references public.users (id) on delete set null;

comment on column public.messages.forwarded_from is
  'Кто написал это изначально. Пусто — сообщение своё, не пересланное.';
