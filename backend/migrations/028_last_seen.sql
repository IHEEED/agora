-- 028: когда человек последний раз заходил.
--
-- Выполнять в Supabase → SQL Editor целиком. Скрипт идемпотентный.
--
-- Нужно ровно для одного: посчитать, сколько людей в сети прямо сейчас. Пока
-- сеть маленькая, это единственное число, по которому видно, живёт она или
-- растёт только в таблице пользователей.
--
-- Отметка времени, а не «онлайн/офлайн» флагом. Флаг требует, чтобы кто-то
-- честно снял его при уходе, а уходят из приложения не кнопкой «выйти», а
-- закрывая вкладку, теряя связь или блокируя телефон. Отметка же не врёт
-- никогда: она говорит, когда человека видели, а «в сети» из неё выводится
-- сравнением с часами.
alter table public.users add column if not exists last_seen_at timestamptz;

-- Считают по нему всегда одним и тем же вопросом: «кого видели за последние
-- пять минут». Частичный индекс здесь не подойдёт — граница подвижная.
create index if not exists users_last_seen_idx on public.users (last_seen_at desc);

comment on column public.users.last_seen_at is
  'Когда человека видели последний раз. Пишется не чаще раза в минуту (см. middleware/auth).';
