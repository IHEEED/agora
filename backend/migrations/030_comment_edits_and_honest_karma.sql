-- 030: правка и удаление комментариев, карма без самоголосов.
--
-- 1. edited_at — комментарий поправлен автором. Показываем «изменено»: на него
--    могли уже ответить, и ответ на слова, которых больше нет, без пометки
--    выглядит ответом невпопад.
--
-- 2. deleted_at — комментарий удалён, но на него успели ответить. Удалить
--    строку нельзя: parent_comment_id каскадный, и вместе с одним своим
--    комментарием человек стёр бы чужие ответы. Сервер не отдаёт у такого
--    комментария ни текста, ни автора — остаётся пустое место в ветке.
--
-- 3. Карма заново — только из голосов других людей.
--    Прогон перед выпуском нашёл: из 21 голоса в базе 15 были отданы авторами
--    за собственные записи и комментарии, и они добавили карме +11. Сервер
--    больше не засчитывает голос за своё в карму, а этот пересчёт убирает то,
--    что накопилось до исправления. Цифры влияния в профилях уменьшатся — это
--    и есть честные цифры.

alter table public.comments add column if not exists edited_at timestamptz;
alter table public.comments add column if not exists deleted_at timestamptz;

update public.users u
set karma = coalesce((
  select sum(v.value)
  from public.votes v
  left join public.posts p on p.id = v.post_id
  left join public.comments c on c.id = v.comment_id
  where coalesce(p.author_id, c.author_id) = u.id
    and v.user_id <> u.id
), 0);

