-- 026: один код — сколько угодно людей.
--
-- Выполнять в Supabase → SQL Editor целиком. Скрипт идемпотентный.
--
-- ── Что было и почему меняем ────────────────────────────────────────────────
--
-- Приглашение было одноразовым: у кода есть used_by и used_at, а у человека —
-- счётчик invites_left, который списывался при выдаче. Модель понятная и в
-- закрытых сетях обычная, но она делает из приглашения дефицит: чтобы позвать
-- троих, надо трижды зайти в настройки и трижды переслать разные строки.
--
-- Дефицит имел бы смысл, если бы им кого-то сдерживали. Здесь он не сдерживает
-- никого: пять кодов раздаются за вечер, а закрытость держится не количеством,
-- а тем, что случайный человек кода не найдёт вовсе. Одна строка, которую можно
-- отдать хоть десятерым, закрытость не отменяет, а работу упрощает вдвое.
--
-- ── Что делаем ──────────────────────────────────────────────────────────────
--
-- Кто пришёл по коду — теперь отдельная таблица, а не пара колонок. Колонки
-- вмещали ровно одного, и превратить их в «многих» без второй таблицы нельзя.
-- Заодно появляется то, чего раньше не было: список приведённых по каждому
-- коду, а не только «использован или нет».
--
-- Требует выполненной 015.

-- ── Кто пришёл по коду ──────────────────────────────────────────────────────
create table if not exists public.invite_uses (
  code text not null references public.invites (code) on delete cascade,
  -- Один человек проходит по коду один раз: второй регистрации у него не
  -- бывает. Первичный ключ по паре и есть эта гарантия.
  user_id uuid not null references public.users (id) on delete cascade,
  used_at timestamptz not null default now(),
  primary key (code, user_id)
);

create index if not exists invite_uses_code_idx on public.invite_uses (code, used_at desc);

alter table public.invite_uses enable row level security;

-- Видит только тот, чей код: список приведённых — не общее знание.
drop policy if exists invite_uses_read on public.invite_uses;
create policy invite_uses_read on public.invite_uses
  for select
  using (
    exists (
      select 1 from public.invites i
       where i.code = invite_uses.code
         and i.issued_by = auth.uid()
    )
  );

-- ── Переносим то, что уже использовано ──────────────────────────────────────
--
-- Без переноса история пропала бы: коды, по которым уже пришли люди, выглядели
-- бы неиспользованными, и в списке у пригласившего стало бы пусто.
insert into public.invite_uses (code, user_id, used_at)
select code, used_by, coalesce(used_at, created_at)
  from public.invites
 where used_by is not null
on conflict (code, user_id) do nothing;

-- ── Снимаем одноразовость ───────────────────────────────────────────────────
--
-- Ограничение «использован — значит известно кем и когда» держало пару колонок
-- в согласии. Колонки остаются (по ним ещё читает старый код до выкладки), но
-- согласованными их больше никто не держит, и проверка стала бы мешать.
alter table public.invites drop constraint if exists invites_used_together;

-- Триггер списания снимаем вместе с функцией: списывать больше нечего.
drop trigger if exists invites_spend on public.invites;
drop function if exists public.spend_invite_on_issue();

-- Счётчик оставляем в схеме, но перестаём им ограничивать. Удалить колонку
-- нельзя, пока на неё смотрит выложенный код: между миграцией и выкладкой
-- всегда есть промежуток, и в нём выборка с несуществующей колонкой упала бы
-- целиком (см. backend/src/config/schema.ts — этот урок уже был).
comment on column public.users.invites_left is
  'Не используется с миграции 026: приглашения безлимитные. Колонка оставлена, чтобы не ронять выборки старого кода.';

comment on column public.invites.used_by is
  'Историческое: первый пришедший по коду. Кто пришёл на самом деле — в invite_uses.';
