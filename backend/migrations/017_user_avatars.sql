-- 017. Лицо у пользователя.
--
-- До этого аватарка жила в localStorage: человек ставил её себе и видел только
-- сам, а собеседник — общий силуэт. Для приложения, где люди разговаривают,
-- это хуже, чем отсутствие аватарок вовсе: свою ты видишь, а значит уверен,
-- что её видят все.
--
-- Колонка, а не отдельная таблица: у пользователя одна аватарка, и связь
-- один-к-одному через таблицу означала бы join на каждой выдаче ленты ради
-- одной строки.
--
-- Ссылка, а не двоичные данные. Файл кладётся в Storage, сюда попадает адрес.
-- Хранить картинки в Postgres дороже по всем статьям: они раздувают резервные
-- копии, их нельзя отдать через CDN и нельзя преобразовать на лету.
--
-- Требует выполненной 004 (public.users).

alter table public.users add column if not exists avatar_url text;

-- Комментарий в схеме — чтобы через полгода не гадать, что здесь ожидается.
comment on column public.users.avatar_url is
  'Полный адрес картинки. Пусто — значит показываем силуэт по умолчанию.';
