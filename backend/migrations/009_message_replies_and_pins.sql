-- 009: ответы на сообщения и закреплённые сообщения.
--
-- Выполнять в Supabase → SQL Editor целиком. Скрипт идемпотентный.
-- Требует выполненной миграции 007 (таблица public.messages).

-- На какое сообщение это ответ.
--
-- Ссылка на само сообщение, а не копия его текста в теле ответа. Копия
-- выглядит так же ровно до первой правки оригинала: после неё цитата
-- показывает то, чего собеседник уже не писал. При on delete set null
-- удалённый оригинал превращает ответ в обычное сообщение, а не утаскивает
-- его за собой.
alter table public.messages
  add column if not exists reply_to_id uuid references public.messages (id) on delete set null;

-- Оригиналы подтягиваются пачкой по открытой переписке.
create index if not exists messages_reply_to_idx
  on public.messages (reply_to_id)
  where reply_to_id is not null;

-- Когда сообщение закрепили. Отметка времени, а не флаг: закреплённых может
-- быть несколько, и показывать их нужно в порядке закрепления.
--
-- Колонка на самом сообщении, а не отдельная таблица: закрепление в личной
-- переписке общее для обоих собеседников — это свойство разговора, а не
-- личная пометка. Личные пометки потребовали бы пары (сообщение, человек),
-- то есть той самой таблицы, и её здесь заводить преждевременно.
alter table public.messages add column if not exists pinned_at timestamptz;

-- Закреплённые выбираются по всей переписке, поэтому частичный индекс:
-- закреплённых единицы на сотни сообщений.
create index if not exists messages_pinned_idx
  on public.messages (pinned_at)
  where pinned_at is not null;
