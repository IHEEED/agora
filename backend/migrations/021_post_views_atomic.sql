-- 021: просмотры считаются в базе, а не в приложении.
--
-- Выполнять в Supabase → SQL Editor целиком. Скрипт идемпотентный.
--
-- Что было. Приложение читало `views`, прибавляло единицу и записывало обратно:
-- два запроса и промежуток между ними. Двое открывших запись одновременно
-- прочитают одно и то же число и запишут одно и то же — из двух просмотров
-- останется один. На своей машине это невидимо: одновременность там не с кем
-- устроить. В ленте у живых людей — обычное дело.
--
-- Прибавление на стороне базы атомарно: `views = views + 1` выполняется под
-- блокировкой строки, и потеряться там нечему. Заодно это один поход в базу
-- вместо двух.

create or replace function public.bump_post_views(target uuid)
returns integer
language sql
security definer set search_path = public
as $function$
  update public.posts
     set views = views + 1
   where id = target
  returning views;
$function$;

-- Сортировка «популярные» читает записи по просмотрам. Без индекса это чтение
-- всей таблицы на каждое открытие главной.
create index if not exists posts_views_idx on public.posts (views desc);
