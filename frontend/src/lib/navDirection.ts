'use client';

/**
 * Куда сейчас идёт навигация: вглубь или назад.
 *
 * Приезд экрана и возврат к нему — разные события, и показывать их одинаково
 * нельзя. Экран, куда пришли впервые, стоит показать движением: он новый, за
 * ним следят. Экран, к которому вернулись, уже был перед глазами секунду
 * назад — его «появление» читается не как переход, а как задержка: лента
 * медленно проявляется вместо того, чтобы просто оказаться на месте.
 *
 * Отличить одно от другого React Router не даёт: pathname меняется одинаково.
 * Поэтому направление помечает тот, кто уводит навигацию назад, — а
 * PageTransition читает пометку в том же кадре, в котором меняется маршрут.
 *
 * Живёт в модуле, а не в состоянии: значение нужно ровно на один рендер и
 * между двумя компонентами, которые друг о друге не знают.
 */
let goingBack = false;

/** Позвать перед router.back(). Пометка снимается первым же чтением. */
export function markGoingBack() {
  goingBack = true;
  // Страховка: если навигация почему-то не случится (жест отменили, маршрут
  // тот же), пометка не должна пережить этот кадр и погасить анимацию
  // следующего, настоящего перехода.
  window.setTimeout(() => {
    goingBack = false;
  }, 400);
}

/** Идём назад? Чтение снимает пометку — она одноразовая. */
export function consumeGoingBack(): boolean {
  const was = goingBack;
  goingBack = false;
  return was;
}
