'use client';

/**
 * Виброотклик на действие.
 *
 * Экран не отвечает на касание ничем, кроме картинки, и на телефоне это
 * заметно: палец закрывает собой кнопку ровно в тот момент, когда та
 * подсвечивается. Короткий толчок подтверждает нажатие раньше, чем глаз
 * успевает проверить результат, — тем же способом, что системная клавиатура и
 * переключатели в iOS.
 *
 * Длительности намеренно крошечные. Всё, что дольше пары десятков
 * миллисекунд, читается не как отклик, а как уведомление — и начинает
 * раздражать на десятом нажатии.
 *
 * navigator.vibrate есть не везде: iOS Safari его не поддерживает вовсе, и это
 * не повод ставить проверки по месту вызова — здесь тихо ничего не делаем.
 * На iOS настоящий Taptic Engine доступен только нативному приложению, ради
 * него и написан мобильный клиент (см. mobile/).
 */
type Strength =
  /** Нажатие: голос, репост, вкладка, кнопка. Самое частое. */
  | 'tap'
  /** Появление чего-то поверх: меню, шторка, просмотр. */
  | 'open'
  /** Порог пройден: край списка отпустил, жест сработал. */
  | 'unlock';

const PATTERN: Record<Strength, number | number[]> = {
  tap: 8,
  open: 12,
  // Два коротких толчка через паузу: «щёлкнуло и открылось». Один такой же
  // длины читался бы просто как более сильное нажатие.
  unlock: [10, 40, 18],
};

export function haptic(strength: Strength = 'tap') {
  if (typeof navigator === 'undefined' || typeof navigator.vibrate !== 'function') return;
  // Системная настройка «уменьшить движение» — про вестибулярный дискомфорт, а
  // не про вибрацию, поэтому её здесь не читаем. Отключается вибрация
  // системно, на уровне телефона, и это правильное место.
  try {
    navigator.vibrate(PATTERN[strength]);
  } catch {
    // Некоторые браузеры бросают, если вкладка не в фокусе. Отклик на действие,
    // которого никто не видит, не нужен — молчим.
  }
}
