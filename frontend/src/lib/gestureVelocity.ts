'use client';

/**
 * Скорость пальца в момент отпускания.
 *
 * Все свайпы в приложении решали по расстоянию: утащил дальше порога —
 * сработало, не дотащил — вернулось. Для медленного, разглядывающего движения
 * это верно, а для щелчка — нет. Короткий резкий флик пальцем проходит
 * тридцать пикселей за сорок миллисекунд, то есть до порога не доезжает и не
 * срабатывает — при том что человек сделал самое решительное движение, на
 * какое способен. Ощущается это как «не послушалось».
 *
 * Поэтому у решения два входа: далеко утащил ИЛИ быстро бросил. Так устроены
 * жесты в iOS, и оттуда же взято правило смотреть на знак скорости, а не только
 * на её величину: если палец в последний момент пошёл обратно, значит человек
 * передумал, и доводить начатое нельзя, как бы далеко он ни утащил до этого.
 *
 * Считаем по нескольким последним точкам, а не по двум. Пара соседних событий
 * на быстром движении даёт разброс в разы: браузер шлёт их неравномерно, и один
 * задержавшийся кадр превращает спокойное движение в мнимый рывок.
 */

/** Сколько последних точек храним. Четырёх хватает, чтобы сгладить дрожь. */
const SAMPLES = 4;

/**
 * Старше этого точки не учитываем.
 *
 * Палец, замерший перед отпусканием, — это отказ от броска, а не бросок. Без
 * срока давности замершая рука донесла бы до отпускания скорость, набранную
 * полсекунды назад, и отпущенный на месте элемент улетал бы сам по себе.
 */
const STALE_MS = 90;

type Sample = { value: number; at: number };

export class VelocityTracker {
  private samples: Sample[] = [];

  /** Забыть всё. Звать в начале жеста. */
  reset(): void {
    this.samples = [];
  }

  /** Записать положение. Звать на каждом движении указателя. */
  add(value: number): void {
    this.samples.push({ value, at: performance.now() });
    if (this.samples.length > SAMPLES) this.samples.shift();
  }

  /**
   * Скорость в пикселях в секунду. Знак — направление движения.
   *
   * Ноль означает «нечего сказать»: точек мало или они устарели. Это честнее
   * выдуманного числа — вызывающий сам решит, что делать без скорости, и
   * обычно это «смотреть на расстояние», то есть прежнее поведение.
   */
  get(): number {
    const now = performance.now();
    const fresh = this.samples.filter((sample) => now - sample.at < STALE_MS);
    if (fresh.length < 2) return 0;

    const first = fresh[0];
    const last = fresh[fresh.length - 1];
    const seconds = (last.at - first.at) / 1000;
    if (seconds <= 0) return 0;

    return (last.value - first.value) / seconds;
  }
}

/**
 * Порог броска, пикселей в секунду.
 *
 * Полтысячи — примерно граница между «веду» и «бросил». Ниже неё быстрые, но
 * осмысленные движения (человек тащит и смотрит) не должны срабатывать раньше
 * времени; выше — уже щелчок, и другого объяснения ему нет.
 */
export const FLICK_SPEED = 500;

/**
 * Сработал ли жест: далеко утащили или быстро бросили.
 *
 * @param distance Сколько прошли, со знаком.
 * @param velocity Скорость на отпускании, со знаком.
 * @param threshold Расстояние, после которого срабатывает и без скорости.
 */
export function committed(distance: number, velocity: number, threshold: number): boolean {
  // Палец в последний момент пошёл обратно — передумали. Расстояние при этом
  // может быть любым: важно, куда двигались, когда отпускали.
  if (velocity !== 0 && Math.sign(velocity) !== Math.sign(distance)) return false;

  if (Math.abs(distance) >= threshold) return true;

  // Бросок засчитываем только если он всё-таки сдвинул с места: иначе дрожь
  // пальца на неподвижном элементе читалась бы как жест.
  return Math.abs(velocity) >= FLICK_SPEED && Math.abs(distance) > threshold * 0.35;
}
