'use client';

import { Message } from './types';

/**
 * Что переслали и кому — на время перехода между экранами.
 *
 * Раньше пересылка отправляла сразу: выбрал человека в списке — реплики ушли.
 * Между «нажал» и «отправлено» не было ни секунды, чтобы понять, туда ли ты
 * нажал, а список получателей — ровно то место, где промахнуться проще всего.
 * И подписать пересылаемое было негде, хотя половина пересылок именно ради
 * подписи и делается: «смотри, что пишут».
 *
 * Теперь открывается сама переписка с готовым черновиком, и отправляет человек
 * сам — как в Telegram. Здесь лежит то, что не проходит через адрес: сами
 * реплики.
 *
 * Модульная переменная, а не хранилище браузера. Это состояние живёт секунду,
 * между нажатием и открытием экрана, и переживать перезагрузку ему не нужно —
 * наоборот, черновик, всплывший через день, был бы неприятной неожиданностью.
 * Тот же приём, что у foldOrigin.
 */
type Pending = {
  messages: Message[];
  /** Из чьей переписки взяли — им и подпишем пересланное. */
  fromUserId: string;
};

let pending: Pending | null = null;

export function setPendingForward(next: Pending) {
  pending = next;
}

/**
 * Забрать и сразу забыть.
 *
 * Одноразовость обязательна: экран переписки читает это на монтировании, и
 * оставшийся черновик всплыл бы при следующем заходе в тот же чат — человек
 * его туда не клал и не поймёт, откуда он взялся.
 */
export function takePendingForward(): Pending | null {
  const value = pending;
  pending = null;
  return value;
}
