'use client';

/**
 * Общая арифметика жестов: скорость, сопротивление на краю, проекция броска.
 *
 * Раньше каждое жестовое место считало по-своему, и решения принимались по
 * пройденному расстоянию: «утянул на 120 точек — закрываем». Для медленной
 * протяжки это верно, а для щелчка нет — короткий быстрый бросок вниз
 * означает «убери», но до порога не доходит, и шторка возвращается. Человек
 * при этом уверен, что уже её выкинул.
 *
 * Отсюда правило: расстояние отвечает за «дотянул до конца», скорость — за
 * «бросил». Достаточно любого из двух.
 */

/** Сколько последних точек держим. Трёх хватает, чтобы сгладить дрожь пальца. */
const HISTORY = 3;

type Sample = { value: number; time: number };

/**
 * Скорость в точках за секунду.
 *
 * Не «за кадр» и не «за событие»: события приходят с частотой экрана, и на
 * ProMotion в iPhone их вдвое больше, чем на обычной матрице. Считая в кадрах,
 * получаешь жест, который на разных телефонах ведёт себя по-разному, — и
 * заметить это на своей машине невозможно.
 */
export class VelocityTracker {
  private samples: Sample[] = [];

  reset(value: number) {
    this.samples = [{ value, time: performance.now() }];
  }

  add(value: number) {
    this.samples.push({ value, time: performance.now() });
    if (this.samples.length > HISTORY) this.samples.shift();
  }

  /** Точек в секунду. Ноль, если считать не по чему. */
  get velocity(): number {
    if (this.samples.length < 2) return 0;

    const first = this.samples[0];
    const last = this.samples[this.samples.length - 1];
    const seconds = (last.time - first.time) / 1000;

    // Палец замер перед отпусканием — это не бросок, а аккуратная укладка.
    // Делить на почти ноль здесь значит получить бесконечность на ровном месте.
    if (seconds < 0.001) return 0;

    return (last.value - first.value) / seconds;
  }
}

/**
 * Сопротивление за границей.
 *
 * Чем дальше тянут за край, тем меньше элемент следует за пальцем. Жёсткий
 * упор читается как «зависло», а нарастающее сопротивление — как «тянуть
 * можно, но дальше ничего нет». Формула Apple из образцов к докладу.
 */
export function rubberband(overshoot: number, dimension: number, constant = 0.55): number {
  const limit = dimension + constant * Math.abs(overshoot);
  return (overshoot * dimension * constant) / limit;
}

/**
 * Куда доедет брошенное.
 *
 * Экспоненциальное затухание, как у прокрутки: не школьное v²/2a, а то, что
 * действительно стоит в iOS. Нужно, чтобы выбирать точку прилипания по тому,
 * куда жест летит, а не по тому, где палец оторвался.
 */
export function project(velocity: number, decelerationRate = 0.998): number {
  return ((velocity / 1000) * decelerationRate) / (1 - decelerationRate);
}

/**
 * Затухание, не зависящее от частоты кадров.
 *
 * `velocity *= 0.94` на кадр — это «за 60 кадров скорость упадёт в 40 раз» на
 * обычном экране и «за 120» на ProMotion, то есть вдвое быстрее по времени.
 * Возводим в степень от прошедших миллисекунд, и затухание становится
 * свойством секунды, а не кадра.
 *
 * Множитель — доля скорости, остающаяся через секунду. 0.004 значит, что за
 * секунду от броска остаётся четверть процента: лента доезжает и встаёт, а не
 * уплывает через полэкрана после того, как палец уже убрали. Значение подобрано
 * руками на ленте историй — на глаз это единственный способ, никакая формула не
 * скажет, длинный бросок или нет.
 */
export function decay(velocity: number, elapsedMs: number, perSecond = 0.004): number {
  return velocity * Math.pow(perSecond, elapsedMs / 1000);
}

/**
 * Бросок это или нет.
 *
 * Порог в 500 точек в секунду — примерно та граница, ниже которой движение
 * ощущается как перенос, а выше как швырок. Знак важнее величины: тянули вниз
 * и отпустили с движением вниз — закрываем, независимо от того, докуда дотянули.
 */
export const FLICK_VELOCITY = 500;

export function isFlick(velocity: number, direction: 1 | -1 = 1): boolean {
  return velocity * direction > FLICK_VELOCITY;
}
