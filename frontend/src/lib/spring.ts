'use client';

/**
 * Пружина: движение, которое можно перехватить на полпути.
 *
 * Все жесты в приложении возвращались на место CSS-переходом. Переход владеет
 * свойством до конца своей длительности — схватить уезжающий элемент и повести
 * обратно нельзя, он сначала доедет. Для интерфейса, где всё тянут пальцем, это
 * главная поломка: мысль и жест происходят одновременно, а интерфейс требует
 * дождаться конца анимации, прежде чем передумать.
 *
 * Пружина устроена иначе. У неё нет длительности — есть текущее положение,
 * текущая скорость и цель. Сменить цель можно в любой момент: скорость при этом
 * сохраняется, и движение продолжается непрерывно, без скачка и без «кирпичной
 * стены» на развороте.
 *
 * ── Почему своя, а не библиотека ────────────────────────────────────────────
 *
 * У проекта пять зависимостей всего. Motion в полном виде — полсотни килобайт
 * ради пяти мест, каждое из которых укладывается в «доехать до числа». Здесь
 * ровно то, что нужно этим пяти, и ни строчки сверх.
 *
 * ── Параметры ───────────────────────────────────────────────────────────────
 *
 * Не жёсткость с массой, а два числа, которыми думают в Apple:
 *
 *   response — за сколько секунд примерно доезжает. Меньше — резче.
 *   damping  — 1.0 без перелёта, ниже 1.0 с отскоком.
 *
 * По умолчанию 1.0: перелёт уместен там, где жест сам нёс инерцию (бросок,
 * флик), и неуместен там, где просто вернули на место.
 */

export type SpringOptions = {
  /** Откуда начинаем. Обычно — текущее положение на экране. */
  from: number;
  /** Куда едем. */
  to: number;
  /** Начальная скорость, пикселей в секунду. Сюда передают скорость пальца. */
  velocity?: number;
  /** За сколько секунд примерно доезжает. */
  response?: number;
  /** 1.0 — без перелёта, меньше — с отскоком. */
  damping?: number;
  onUpdate: (value: number) => void;
  onDone?: () => void;
};

export type SpringHandle = {
  /** Сменить цель на ходу. Скорость сохраняется — в этом весь смысл. */
  to: (next: number) => void;
  /** Текущее положение: с него начинают, когда жест перехватывает движение. */
  value: () => number;
  /** Текущая скорость: её передают дальше, чтобы не было разрыва. */
  velocity: () => number;
  stop: () => void;
};

/** Ближе этого к цели и медленнее этого — считаем, что приехали. */
const REST_DISTANCE = 0.4;
const REST_VELOCITY = 4;

export function spring({
  from,
  to,
  velocity = 0,
  response = 0.35,
  damping = 1,
  onUpdate,
  onDone,
}: SpringOptions): SpringHandle {
  let x = from;
  let v = velocity;
  let target = to;
  let frame = 0;
  let last = performance.now();

  // Частота из времени отклика: чем короче response, тем туже пружина.
  const omega = (2 * Math.PI) / response;
  const stiffness = omega * omega;
  const friction = 2 * damping * omega;

  const step = (now: number) => {
    // Шаг ограничиваем сверху. Вкладка, которую свернули и вернули, отдаёт
    // первый кадр с разрывом в секунды — без ограничения пружина за один такой
    // кадр улетает в бесконечность и элемент исчезает с экрана.
    const dt = Math.min((now - last) / 1000, 1 / 30);
    last = now;

    // Полунеявный Эйлер: сначала обновляем скорость, потом по ней положение.
    // Явный вариант на тугих пружинах расходится — амплитуда растёт вместо
    // того, чтобы гаснуть.
    const acceleration = -stiffness * (x - target) - friction * v;
    v += acceleration * dt;
    x += v * dt;

    if (Math.abs(x - target) < REST_DISTANCE && Math.abs(v) < REST_VELOCITY) {
      // Дотягиваем ровно до цели: остановиться в четверти пикселя от неё
      // означает накопить сдвиг за десяток жестов.
      x = target;
      v = 0;
      onUpdate(x);
      onDone?.();
      return;
    }

    onUpdate(x);
    frame = requestAnimationFrame(step);
  };

  frame = requestAnimationFrame(step);

  return {
    to: (next: number) => {
      target = next;
    },
    value: () => x,
    velocity: () => v,
    stop: () => cancelAnimationFrame(frame),
  };
}
