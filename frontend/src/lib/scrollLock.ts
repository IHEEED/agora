'use client';

/**
 * Запрет прокрутки страницы, пока сверху что-то открыто.
 *
 * Раньше каждая накладка делала это сама: запоминала прежнее значение
 * `body.style.overflow`, ставила `hidden`, а на закрытии возвращала
 * запомненное. Приём выглядит аккуратным ровно до второй накладки.
 *
 * На экране переписок их три — шторка «кому написать», меню действий по строке
 * и окно подтверждения удаления. Открывается первая: запомнила «пусто»,
 * поставила `hidden`. Пока она открыта, открывается вторая: запомнила уже
 * `hidden`. Закрываются в любом порядке — и та, что закрылась последней,
 * возвращает `hidden`. Страница остаётся заблокированной навсегда, при том что
 * на ней ничего не открыто.
 *
 * Со стороны это выглядит так: открыл список людей, закрыл, и переписки
 * перестали листаться. Причём «перестали» до перезагрузки, потому что вернуть
 * прокрутку в интерфейсе нечем — она не выключалась ничем видимым.
 *
 * Отсюда счётчик. Значение «сколько накладок сейчас хотят тишины» — общее, и
 * знать его должен один, а не пятеро по отдельности. Блокируем на переходе
 * 0 → 1, отпускаем на 1 → 0, а между ними ничего не трогаем.
 */

let depth = 0;

/** Что стояло до самой первой блокировки. Восстанавливаем только это. */
let original: string | null = null;

/**
 * Заблокировать прокрутку. Возвращает функцию снятия — звать ровно один раз.
 *
 * Возврат функции, а не парный `unlock()`, намеренно: так снятие невозможно
 * забыть привязать к тому же самому вызову, и его естественно вернуть из
 * useEffect как уборку.
 */
export function lockScroll(): () => void {
  if (typeof document === 'undefined') return () => {};

  if (depth === 0) {
    original = document.body.style.overflow;
    document.body.style.overflow = 'hidden';
  }
  depth += 1;

  // Защита от повторного снятия. React в отладочном режиме вызывает уборку
  // эффекта дважды, и без этого флага счётчик уходил бы в минус — а значит
  // следующая накладка не заблокировала бы ничего.
  let released = false;

  return () => {
    if (released) return;
    released = true;
    depth = Math.max(0, depth - 1);
    if (depth === 0) {
      document.body.style.overflow = original ?? '';
      original = null;
    }
  };
}
