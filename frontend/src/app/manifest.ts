import type { MetadataRoute } from 'next';

/**
 * Манифест — то, что превращает вкладку в приложение на телефоне.
 *
 * Нужен ради display: 'standalone'. Без него добавленное на экран «Домой»
 * открывается обычной вкладкой Safari — с адресной строкой сверху и панелью
 * снизу, которые отъедают полтора сантиметра как раз там, где у нас шапка и
 * бар. С ним окно отдаётся приложению целиком, и жест «назад» по краю экрана
 * достаётся нашему свайпу, а не браузеру.
 *
 * Это же — самый быстрый способ посмотреть текущую версию на iPhone: она
 * приезжает вся, без переноса экранов заново, и обновляется сама.
 */
export default function manifest(): MetadataRoute.Manifest {
  return {
    name: 'PARAFRAZ',
    short_name: ':P',
    description: 'Соцсеть, где мысль важнее ленты',
    start_url: '/',
    display: 'standalone',
    // Строка состояния и подложка окна на запуске. Тёмная — потому что первый
    // кадр рисуется до того, как приложение узнает выбранную тему, и светлая
    // вспышка на тёмной теме заметнее, чем тёмная на светлой.
    background_color: '#0b0910',
    theme_color: '#0b0910',
    orientation: 'portrait',
    icons: [
      { src: '/icon.svg', sizes: 'any', type: 'image/svg+xml' },
      { src: '/apple-icon', sizes: '180x180', type: 'image/png' },
    ],
  };
}
