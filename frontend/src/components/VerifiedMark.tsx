'use client';

/**
 * Галочка рядом с ником.
 *
 * Отвечает ровно на один вопрос: «этот человек — тот, за кого себя выдаёт».
 * Не про важность, не про число подписчиков и не про заслуги — в сети, где ник
 * берут почти любой, единственная защита от подделки это чья-то проверка.
 *
 * Отдельным компонентом, а не разметкой по местам: ник показан в двенадцати
 * файлах, и галочка, расставленная вручную, в половине из них рано или поздно
 * окажется другого размера или другого цвета.
 *
 * Ничего не рисует, когда галочки нет, — можно ставить безусловно.
 */
/**
 * Цвет не из палитры оформления, а свой.
 *
 * Акцент у каждой темы разный: в «Хронике» он охряный, в «Гламуре» розовый.
 * Галочка, покрашенная акцентом, в одной теме читалась бы значком, а в другой
 * — украшением заголовка, и одно и то же обозначение выглядело бы шестью
 * разными способами.
 *
 * А значение у неё одинаковое всегда, и узнаваться она должна с первого
 * взгляда. Поэтому цвет зашит: тот самый голубой, которым галочку рисуют
 * везде, где её вообще рисуют. Это единственное место в приложении, где
 * зашитый цвет — не небрежность, а смысл.
 */
const VERIFIED_BLUE = '#1d9bf0';

export function VerifiedMark({
  verified,
  size = 17,
}: {
  /** Дата подтверждения. Пусто — значка нет. */
  verified?: string | null;
  size?: number;
}) {
  if (!verified) return null;

  return (
    <span
      className="inline-flex flex-none items-center align-middle"
      style={{ color: VERIFIED_BLUE }}
      title="Подлинность подтверждена"
      aria-label="Подтверждённый аккаунт"
    >
      <svg width={size} height={size} viewBox="0 0 24 24" fill="none">
        {/* Залитая розетка с галочкой внутри, а не контурная птичка.
            Контур на мелком кегле сливается в серое пятно: линии тоньше
            пикселя, и браузер размазывает их по субпикселям. Заливка держит
            форму на любом размере. */}
        <path
          fill="currentColor"
          d="M12 2.2l2.06 1.6 2.6-.23.86 2.47 2.25 1.32-.7 2.52.7 2.52-2.25 1.32-.86 2.47-2.6-.23L12 21.8l-2.06-1.6-2.6.23-.86-2.47-2.25-1.32.7-2.52-.7-2.52 2.25-1.32.86-2.47 2.6.23z"
        />
        <path
          d="m8.6 12.2 2.3 2.3 4.5-4.7"
          fill="none"
          // Белая, а не цветом фона: на тёмной теме галочка внутри синей
          // розетки должна оставаться светлой, иначе она пропадает.
          stroke="#ffffff"
          strokeWidth="2.1"
          strokeLinecap="round"
          strokeLinejoin="round"
        />
      </svg>
    </span>
  );
}
