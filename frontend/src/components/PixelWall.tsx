/**
 * Фон экрана входа — четыре огромных цветных пятна, медленно перетекающих
 * друг в друга.
 *
 * До этого здесь лежала пиксельная надпись PARAFRAZ, размноженная сеткой
 * сорок на двенадцать и уезжающая вбок. Помимо того, что это выглядело как
 * заставка пиратской сборки, у приёма была и техническая цена: почти пятьсот
 * узлов DOM с текстом, каждый со своим кеглем и прозрачностью, — и всё это
 * ради фона, на который никто не смотрит дольше секунды.
 *
 * Здесь узлов четыре, и двигаются они трансформацией, то есть на видеокарте.
 * Цвет берётся от акцента выбранного стиля: вход сразу показывает, какого
 * цвета приложение внутри, а не живёт отдельной картинкой.
 *
 * Имя файла и компонента прежнее намеренно — он подключён в AuthScreen, и
 * переименование ради переименования только запутало бы историю правок.
 */

/** Насколько каждое пятно смещено от центра, в процентах экрана. */
const BLOBS = [
  { top: '-18%', left: '-12%', size: '78vmax', delay: '0s', tint: 'var(--accent)' },
  { top: '8%', left: '52%', size: '64vmax', delay: '-9s', tint: 'var(--accent)' },
  { top: '48%', left: '-20%', size: '70vmax', delay: '-18s', tint: 'var(--accent)' },
  { top: '54%', left: '40%', size: '82vmax', delay: '-27s', tint: 'var(--accent)' },
];

export function PixelWall() {
  return (
    <div className="auth-wall" aria-hidden>
      {BLOBS.map((blob, index) => (
        <span
          key={index}
          className="auth-blob"
          style={{
            top: blob.top,
            left: blob.left,
            width: blob.size,
            height: blob.size,
            // Отрицательная задержка сдвигает пятна по фазе: без неё все
            // четыре дышали бы разом, и вместо перетекания вышла бы пульсация.
            animationDelay: blob.delay,
            // Разная плотность у соседних пятен — иначе на стыке видно, что
            // это четыре одинаковых круга, а не одно облако.
            opacity: 0.55 + (index % 2) * 0.25,
          }}
        />
      ))}
    </div>
  );
}
