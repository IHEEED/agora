/**
 * Живой фон экрана входа: пиксельный логотип, повторённый под углом,
 * строки медленно едут слева направо.
 *
 * Рисуем настоящим DOM-слоем, а не фоновой картинкой: шрифт подключён через
 * next/font, а внутрь background-image с data-URI внешние шрифты не грузятся —
 * надпись выпала бы в системный шрифт и перестала быть пиксельной.
 */

// Размеры, прозрачность и скорость берём из фиксированных наборов, а не из
// random(): серверный и клиентский рендер обязаны совпасть до пикселя.
// Кегли заданы в em от размера полотна — так весь узор ужимается на телефоне
// одним правилом в CSS, без второго набора чисел здесь.
//
// Длина наборов взаимно проста с шагами обхода ниже: иначе на плотной сетке
// сразу читались бы диагональные полосы из одинаковых надписей.
const SIZES = [1.5, 0.85, 2.6, 1.1, 3.4, 0.7, 1.9, 2.2, 0.95, 2.9, 1.3, 3.9, 0.8, 1.7, 2.4, 1.05, 3.1];
const FADES = [0.7, 1, 0.45, 0.85, 0.6, 1, 0.5, 0.9, 0.65, 0.4, 1, 0.75, 0.55, 0.95, 0.5, 0.8, 0.6];
// Разная длительность у соседних строк даёт лёгкий параллакс: одинаковая
// скорость читалась бы одним сплошным полотном, ползущим вбок.
const DURATIONS = [70, 96, 58, 84, 112, 64, 90, 76, 104, 68, 82];

const ROWS = 40;
const PER_ROW = 12;

export function PixelWall() {
  return (
    <div className="pixel-wall" aria-hidden>
      <div className="pixel-wall-inner">
        {Array.from({ length: ROWS }, (_, row) => (
          <div className="pixel-wall-row" key={row}>
            {/* Содержимое строки продублировано: сдвиг ровно на половину
                собственной ширины возвращает картинку в исходное положение,
                поэтому цикл не виден на стыке. */}
            <div
              className="pixel-wall-track"
              style={{ animationDuration: `${DURATIONS[row % DURATIONS.length]}s` }}
            >
              {Array.from({ length: PER_ROW * 2 }, (_, col) => {
                // Индекс берём по позиции внутри одной копии, иначе половины
                // разошлись бы и стык стал бы заметен.
                const slot = col % PER_ROW;
                // Разные шаги для кегля и прозрачности: если брать оба из
                // одного индекса, крупные надписи всегда самые яркие.
                const size = SIZES[(row * 5 + slot * 3) % SIZES.length];
                const fade = FADES[(row * 7 + slot * 4) % FADES.length];
                return (
                  <span key={col} style={{ fontSize: `${size}em`, opacity: fade }}>
                    PARAFRAZ
                  </span>
                );
              })}
            </div>
          </div>
        ))}
      </div>
    </div>
  );
}
