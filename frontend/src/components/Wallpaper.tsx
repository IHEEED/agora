/**
 * Подложка приложения — два слоя под всем интерфейсом.
 *
 * Раньше здесь лежали четыре цветных пятна по углам экрана. Задумывались они
 * как подсветка под стекло, а вели себя как пятна: сквозь полупрозрачные
 * карточки на текст наползал то оранжевый, то фиолетовый угол. Теперь вместо
 * них один источник света сверху — как окно над страницей — и типографское
 * зерно, из-за которого фон перестаёт выглядеть залитым ровным цветом.
 *
 * Рендерить, кроме самих слоёв, нечего: плотность и того и другого задаёт
 * выбранный стиль через переменные --glow и --grain. Так значения успевают
 * примениться до первой отрисовки, вместе с темой, и ничего не мигает.
 */
export function Wallpaper() {
  return (
    <>
      <div className="app-glow" aria-hidden />
      <div className="app-grain" aria-hidden />
      {/* Обои переписки живут здесь, а не на экране чата.
          Внутри чата этот слой оказывался потомком узла, который PageTransition
          анимирует при въезде: position: fixed привязывается к ближайшему
          предку с transform, поэтому обои ехали и масштабировались вместе с
          экраном — узор было видно, как он догоняет кадр. Отсюда и «рваная
          анимация обоев».

          Здесь слой вне анимируемого дерева и просто стоит на месте. Показывать
          ли его, решает атрибут data-in-chat на <html>, который ставит сам
          экран переписки. */}
      <div className="chat-wallpaper" aria-hidden />
    </>
  );
}
