'use client';

import { useEffect, useState, useSyncExternalStore } from 'react';
import { isFetching, subscribeFetching } from '@/lib/useApiData';

/**
 * Знак приложения: `:P`.
 *
 * Лицо с высунутым языком — интонация «не всерьёз», ровно та, что нужна
 * приложению, где главная механика не «нравится», а «не согласен, давай
 * обсудим». Два знака вместо восьми букв: название читают один раз, а видят
 * каждый заход.
 *
 * Скобки вокруг были попыткой сделать из знаков логотип — замкнуть их в форму с
 * силуэтом. На деле они добавляли к двум символам ещё два и превращали лёгкую
 * подпись в тяжёлую эмблему.
 *
 * Гротеск, а не газетная антиква. У антиквы засечки и переменная толщина, и на
 * мелком кегле двоеточие с буквой рассыпались на зазубрины; вся ценность знака в
 * том, что он читается с одного взгляда, а значит нужны ровные линии без
 * украшений. Шрифт берём тот же, которым набран интерфейс.
 */
/** Длительность одного моргания. То же число стоит в keyframes. */
const BLINK_MS = 1600;

export function Wordmark({ size = 27 }: { size?: number }) {
  /**
   * Пока лента перечитывается — знак моргает.
   *
   * Спорить тут можно было о многом: крутить спиннер рядом, гасить знак,
   * пульсировать целиком. Но `:P` — это лицо, и у лица уже есть способ
   * показать, что оно занято: моргнуть. Двоеточие на мгновение сжимается в
   * тире, язык чуть подаётся вниз — и всё возвращается.
   *
   * Ничего не двигается и не крутится: знак стоит в центре шапки, и любое
   * движение размером с него самого перетягивало бы внимание с ленты, ради
   * которой человек и обновлял.
   *
   * Одно моргание в цикле, а не бесконечная тряска: если ответ пришёл быстро,
   * человек увидит ровно один кивок — этого хватает, чтобы понять, что его
   * услышали.
   */
  const fetching = useSyncExternalStore(
    subscribeFetching,
    () => isFetching('/posts'),
    () => false
  );

  /**
   * Моргание доигрывает до конца, даже если ответ пришёл раньше.
   *
   * Механика была верной, а срок — нет. Лента с кешем отвечает за две-три сотни
   * миллисекунд, моргание длится полторы секунды, и класс снимали раньше, чем
   * анимация успевала дойти до первого закрытого глаза. Со стороны это выглядит
   * как «анимации нет вовсе» — что и было сказано.
   *
   * Держим до конца цикла. Показать начатое движение до конца важнее, чем точно
   * совпасть с длиной запроса: человек смотрит на знак, а не на секундомер.
   */
  const [blinking, setBlinking] = useState(false);

  useEffect(() => {
    if (!fetching) return;
    setBlinking(true);
    const timer = window.setTimeout(() => setBlinking(false), BLINK_MS);
    return () => window.clearTimeout(timer);
  }, [fetching]);

  const busy = fetching || blinking;

  return (
    <span
      className={`wordmark select-none${busy ? ' wordmark-blink' : ''}`}
      style={{ fontSize: size }}
      aria-hidden
    >
      {/* Двоеточие опущено к оптической середине: рядом с прописной буквой оно
          стоит выше её середины, и лицо съезжает вверх. */}
      <span className="wordmark-eyes">:</span>
      <span className="wordmark-tongue">P</span>
    </span>
  );
}
