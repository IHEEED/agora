/**
 * Знак приложения: `(:P)`.
 *
 * Раньше в шапке стояло слово PARAFRAZ разрядкой — восемь букв, которые на
 * телефоне занимали треть верхней строки и при этом ничего не делали: название
 * человек читает один раз, а видит его каждый заход. Знак должен опознаваться
 * с расстояния и мельче, чем читается слово.
 *
 * Смайл, а не монограмма. `:P` — это лицо с высунутым языком, то есть ровно та
 * интонация, которой в сети говорят «не всерьёз»; для приложения, где главная
 * механика — не согласиться и обсудить, это подходящая подпись. Скобки
 * превращают набор знаков в замкнутую форму, которая работает как логотип: у
 * неё есть силуэт.
 *
 * Собран из отдельных элементов, а не набран текстом, по двум причинам:
 * двоеточие в антикве сидит слишком высоко и требует своей оптической правки, а
 * акцентом красится только буква — в тексте это потребовало бы вложенных span
 * в каждом месте, где знак появляется.
 */
export function Wordmark({ size = 26 }: { size?: number }) {
  return (
    <span
      className="wordmark select-none"
      style={{ fontSize: size }}
      aria-hidden
    >
      <span className="wordmark-bracket">(</span>
      {/* Двоеточие опущено к оптической середине: в антикве оно стоит выше
          строчных, и рядом с буквой лицо «съезжало» вверх. */}
      <span className="wordmark-eyes">:</span>
      <span className="wordmark-tongue">P</span>
      <span className="wordmark-bracket">)</span>
    </span>
  );
}
