'use client';

import { useT } from '@/lib/i18n';

/**
 * Возврат назад: стрелка и слово.
 *
 * Стрелка стояла одна, кружком, на семи экранах — и на каждом была написана
 * заново. Одинаковая по виду, но своя по коду, то есть расходящаяся при первой
 * же правке.
 *
 * Слово рядом — не украшение. Голая стрелка отвечает «отсюда можно выйти», но
 * не отвечает «куда», а это разные вопросы, и второй важнее: человек решает,
 * нажимать ли, по тому, что будет после. В iOS у кнопки возврата подпись есть
 * с самого начала, и убрали её только там, где место дороже ясности.
 *
 * Подпись прячется на узких экранах (`hidden xs:inline`) — но не ради экономии
 * места, а потому что там она уже сказана: заголовок экрана стоит прямо рядом,
 * и «Назад · Настройки» превращается в две подписи об одном.
 */
export function BackButton({
  onClick,
  label,
}: {
  onClick: () => void;
  /**
   * Что написать вместо «Назад». Годится, когда известно, куда именно
   * возвращает: «В ленту» точнее, чем «Назад», и стоит того же места.
   */
  label?: string;
}) {
  const { t } = useT();

  return (
    <button
      type="button"
      onClick={onClick}
      aria-label={label ?? t('common.back')}
      // Вид взят с записи и чужого профиля, где кнопка со словом стояла и
      // раньше: безрамочная, с отрицательным левым полем, чтобы стрелка встала
      // по одной линии с текстом под ней. Стеклянный кружок был у трёх экранов
      // из семи — меньшинство, и это меньшинство как раз без подписи.
      className="-ml-2 flex w-fit flex-none items-center gap-1.5 rounded-full py-2 pl-2 pr-3.5 text-[16px] font-medium text-[var(--text)] transition-colors hover:bg-[var(--surface-2)] active:scale-95"
    >
      <svg
        width="24"
        height="24"
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth="2"
        strokeLinecap="round"
        strokeLinejoin="round"
        className="flex-none"
      >
        <path d="M15 5l-7 7 7 7" />
      </svg>
      <span className="leading-none">{label ?? t('common.back')}</span>
    </button>
  );
}
